//! A-11: compile the generated C ABI header together with a REAL Qt header.
//!
//! `qobjectdefs.h` defines `signals`, `slots` and `emit` as macros, so a field or
//! parameter named after one of them breaks every Qt translation unit that
//! includes `vd_ffi.h`. This test is the compile-level half of the guard (the
//! name-level half is the scanner in `src/capi.rs`); it exists because the
//! `signals` collision took the whole editor lane down on 2026-11-02.
//!
//! The test compiles `tests/qt_abi_guard.cpp` against the header **as it exists
//! in the tree** (`include/vd_ffi.h`, regenerated by build.rs on every build), so
//! a stale header cannot pass. When the host has no Qt6 development files the
//! test prints a loud SKIP with the command it would have run — never a silent
//! pass.

use std::path::{Path, PathBuf};
use std::process::Command;

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// `pkg-config --cflags Qt6Core`, split into arguments; `None` when Qt6 is absent.
fn qt_cflags() -> Option<Vec<String>> {
    let output = Command::new("pkg-config")
        .args(["--cflags", "Qt6Core"])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let text = String::from_utf8_lossy(&output.stdout);
    let flags: Vec<String> = text.split_whitespace().map(str::to_string).collect();
    if flags.is_empty() {
        None
    } else {
        Some(flags)
    }
}

fn gxx() -> Option<PathBuf> {
    let output = Command::new("g++").arg("--version").output().ok()?;
    output.status.success().then(|| PathBuf::from("g++"))
}

#[test]
fn the_generated_header_compiles_together_with_a_real_qt_header() {
    let guard = manifest_dir().join("tests/qt_abi_guard.cpp");
    let include = manifest_dir().join("include");
    let header = include.join("vd_ffi.h");
    assert!(guard.is_file(), "missing guard TU at {}", guard.display());
    assert!(
        header.is_file(),
        "missing generated header at {}: run `cargo build -p vd-ffi` first",
        header.display()
    );

    let (Some(cflags), Some(compiler)) = (qt_cflags(), gxx()) else {
        println!(
            "SKIP: Qt6 development files are not available on this host, so the Qt/ABI compile \
             guard did not run. It would have run:\n  g++ -std=c++17 -fsyntax-only -fPIC \
             $(pkg-config --cflags Qt6Core) -I {} {}",
            include.display(),
            guard.display()
        );
        return;
    };

    let mut command = Command::new(compiler);
    command
        .args(["-std=c++17", "-fsyntax-only", "-fPIC"])
        .args(&cflags)
        .arg("-I")
        .arg(&include)
        .arg(&guard);
    let command_line = format!(
        "g++ -std=c++17 -fsyntax-only -fPIC {} -I {} {}",
        cflags.join(" "),
        include.display(),
        guard.display()
    );
    let output = command
        .output()
        .unwrap_or_else(|error| panic!("running `{command_line}`: {error}"));
    assert!(
        output.status.success(),
        "the generated header does not compile with a real Qt header (macro collision?).\n\
         command: {command_line}\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    println!("QT_ABI_GUARD: PASS ({command_line})");
    let _ = Path::new(&header);
}
