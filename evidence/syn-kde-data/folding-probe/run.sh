#!/usr/bin/env bash
# Build + run the folding probe against the SELF-BUILT (F2) KSyntaxHighlighting.
#
#   bash evidence/syn-kde-data/folding-probe/run.sh [before|after] [resources-dir]
#
# Modes
#   after  (default): measures $RESOURCES/syntax/vedit-{verilog,systemverilog}.xml
#                     (the T45 fixed definitions);
#   before:           measures folding-probe/before/*.xml, the pre-T45 definitions
#                     extracted from git HEAD at T66 time (their sha256 is printed
#                     in the log).
#
# T66 corrections — the previous runner was wrong and its logs are annotated:
#   * library layout: the F2 install prefix is `<...>/F2/install`; the runtime
#     library lives in `<prefix>/lib/x86_64-linux-gnu` and the headers in
#     `<prefix>/include/KF6/KSyntaxHighlighting`. The old
#     `F2_DIR=$(dirname $(dirname "$LIB"))` produced `<prefix>/lib`, so -I and -L
#     pointed at nonexistent directories and g++/ld silently fell back to the
#     DISTRO library while the script still printed library=F2.
#   * the compiled binary's ldd MUST resolve libKF6SyntaxHighlighting inside the
#     F2 install tree; otherwise this script exits 1. No `library=` result line is
#     printed before that proof, so a `library=F2` label can never describe a
#     distro run.
#   * the sample language is passed explicitly (verilog|systemverilog). The old
#     probe selected it with `definitionName == "SystemVerilog"`, but the runner
#     passes the renamed probe definition VEditProbeSystemVerilog, so the SV branch
#     never ran and both runs measured the 18-line Verilog sample.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$HERE/../../.." && pwd)
MODE="${1:-after}"
RESOURCES="${2:-$ROOT/resources}"

case "$MODE" in
  before) SRC="$HERE/before" ;;
  after) SRC="$RESOURCES/syntax" ;;
  *)
    echo "usage: $0 [before|after] [resources-dir]" >&2
    exit 2
    ;;
esac
for file in vedit-verilog.xml vedit-systemverilog.xml; do
  [ -f "$SRC/$file" ] || {
    echo "FATAL: missing $SRC/$file" >&2
    exit 1
  }
done

# Host-side probe data: byte-identical copies apart from the unique definition
# names (so a distro/KDE built-in can never be resolved by accident).
PROBE_DATA="$ROOT/target/fold-probe-data-$MODE"
rm -rf "$PROBE_DATA"
mkdir -p "$PROBE_DATA/syntax"
sed 's/name="Verilog"/name="VEditProbeVerilog"/' \
  "$SRC/vedit-verilog.xml" > "$PROBE_DATA/syntax/vedit-verilog.xml"
sed 's/name="SystemVerilog"/name="VEditProbeSystemVerilog"/' \
  "$SRC/vedit-systemverilog.xml" > "$PROBE_DATA/syntax/vedit-systemverilog.xml"
grep -q 'VEditProbeVerilog' "$PROBE_DATA/syntax/vedit-verilog.xml" || {
  echo "FATAL: probe copy was not renamed" >&2
  exit 1
}
grep -q 'VEditProbeSystemVerilog' "$PROBE_DATA/syntax/vedit-systemverilog.xml" || {
  echo "FATAL: SystemVerilog probe copy was not renamed" >&2
  exit 1
}

echo "# collected_at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "# git_head: $(git -C "$ROOT" rev-parse HEAD)"
echo "# git_status_porcelain (this task's paths):"
git -C "$ROOT" status --porcelain -- resources/syntax evidence/syn-kde-data/folding-probe | sed 's/^/#   /' 
echo "# mode=$MODE source=$SRC"
sha256sum "$SRC/vedit-verilog.xml" "$SRC/vedit-systemverilog.xml" | sed 's/^/# source sha256 /'

user_args=()
if ! docker info --format '{{json .SecurityOptions}}' 2>/dev/null | grep -q '"name=rootless"'; then
  user_args=(--user "$(id -u):$(id -g)")
fi

EXPECT="fold"
[ "$MODE" = "before" ] && EXPECT="zero"
INNER="$ROOT/target/fold-probe-$MODE-inner.sh"

cat > "$INNER" <<'INNER_EOF'
#!/usr/bin/env bash
# Generated by evidence/syn-kde-data/folding-probe/run.sh - read-only probe runner.
set -euo pipefail
MODE="__MODE__"
EXPECT="__EXPECT__"
DATA="/vedit-build/target/fold-probe-data-__MODE__"

LIB=$(find /vedit-build/target/ksh-selfbuild -type f -name 'libKF6SyntaxHighlighting.so.6.*' \
  -path '*/install/lib/*' 2>/dev/null | sort | head -1)
[ -n "$LIB" ] || {
  echo "FATAL: no F2 library under target/ksh-selfbuild" >&2
  exit 1
}
LIBDIR=$(cd "$(dirname "$LIB")" && pwd)
PREFIX=$(cd "$LIBDIR/../.." && pwd)
INCDIR="$PREFIX/include/KF6/KSyntaxHighlighting"
[ -f "$INCDIR/KSyntaxHighlighting/Repository" ] || {
  echo "FATAL: F2 headers missing ($INCDIR/KSyntaxHighlighting/Repository)" >&2
  exit 1
}
[ -f "$INCDIR/ksyntaxhighlighting_version.h" ] || {
  echo "FATAL: F2 version header missing ($INCDIR/ksyntaxhighlighting_version.h)" >&2
  exit 1
}
case "$PREFIX" in
  /vedit-build/target/ksh-selfbuild/F2/install) ;;
  *)
    echo "FATAL: resolved library is not the F2 install: $PREFIX" >&2
    exit 1
    ;;
esac

echo "# F2 install prefix: $PREFIX"
echo "# F2 library: $LIB"
echo "## compile: g++ ... -I$INCDIR -L$LIBDIR -Wl,-rpath,$LIBDIR -lKF6SyntaxHighlighting"
g++ -std=c++20 -O0 -fPIC -o /tmp/fold-probe \
  evidence/syn-kde-data/folding-probe/probe.cpp \
  $(pkg-config --cflags Qt6Core Qt6Gui) -I"$INCDIR" \
  $(pkg-config --libs Qt6Core Qt6Gui) \
  -L"$LIBDIR" -Wl,-rpath,"$LIBDIR" -lKF6SyntaxHighlighting

RESOLVED=$(ldd /tmp/fold-probe | awk '/libKF6SyntaxHighlighting[.]so/{print $3}')
case "$RESOLVED" in
  "$LIBDIR"/*) ;;
  *)
    echo "FATAL: library=F2 requested but ldd resolves ${RESOLVED:-<nothing>} (expected under $LIBDIR)" >&2
    exit 1
    ;;
esac
echo "# ldd guard: libKF6SyntaxHighlighting resolves inside the F2 tree: $RESOLVED"

run_probe() {
  local language="$1"
  local definition="$2"
  local output="/tmp/fold-probe-$language.out"
  echo "# ---- probe language=$language definition=$definition ----"
  # Every result line below carries library=F2; this immediately preceding line is
  # the ldd proof for that label.
  echo "LDD library=F2 resolves=$RESOLVED"
  set +e
  XDG_DATA_HOME=/tmp/vedit-empty-home XDG_DATA_DIRS=/tmp/vedit-empty-data \
    VEDIT_FOLD_PROBE_LIBRARY=F2 \
    /tmp/fold-probe "$DATA" "$definition" "$language" 2>&1 | tee "$output"
  local probe_exit=${PIPESTATUS[0]}
  set -e
  echo "PROBE-EXIT=$probe_exit"
  grep -q 'DEFINITION library=F2 ' "$output" || {
    echo "FATAL: no DEFINITION library=F2 line" >&2
    exit 1
  }
  grep -q 'RESULT library=F2 ' "$output" || {
    echo "FATAL: no RESULT library=F2 line" >&2
    exit 1
  }
  if [ "$EXPECT" = "fold" ]; then
    [ "$probe_exit" = "0" ] || {
      echo "FATAL: expected non-zero folds after the T45 fix, exit=$probe_exit" >&2
      exit 1
    }
    grep -Eq 'begins=[1-9][0-9]* ends=[1-9][0-9]*' "$output" || {
      echo "FATAL: expected non-zero begins/ends" >&2
      exit 1
    }
  else
    [ "$probe_exit" = "1" ] || {
      echo "FATAL: expected the pre-fix zero-fold result (exit 1), got exit=$probe_exit" >&2
      exit 1
    }
    grep -q 'begins=0 ends=0' "$output" || {
      echo "FATAL: expected begins=0 ends=0 for the pre-fix XML" >&2
      exit 1
    }
    grep -q 'Unknown keyword list "module"' "$output" || {
      echo "FATAL: expected the pre-fix keyword-list warnings" >&2
      exit 1
    }
  fi
}

run_probe verilog VEditProbeVerilog
run_probe systemverilog VEditProbeSystemVerilog
echo "PROBE-SUMMARY mode=$MODE expected=$EXPECT all-checks=PASS"
INNER_EOF

sed -i "s/__MODE__/$MODE/g; s/__EXPECT__/$EXPECT/g" "$INNER"

docker run --rm "${user_args[@]}" \
  -v "$ROOT:/vedit-build" -w /vedit-build \
  -e HOME=/tmp -e LANG=C.UTF-8 \
  vedit-qt6-build:local bash "/vedit-build/target/fold-probe-$MODE-inner.sh"
