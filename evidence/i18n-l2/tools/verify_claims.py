#!/usr/bin/env python3
r"""Verify the reconciliation table's `already_wrapped` claim against reality.

T39 FAILED on F3 because `make_reconciliation.py` trusted the discovery CSV's
`already_wrapped` column: the discovery step (`enumerate_b_class.py`) decided
"wrapped" from a **fixed window** around the recorded line, so a raw
`QStringLiteral("saved file")` that merely sat inside a multi-line
`translate(...)` call was recorded as wrapped although the literal itself never
reaches `tr()` and never appears in the .ts.

This module answers the two questions the claim must rest on, per row:

  * `wrap` — is THIS literal an argument of `tr(` / `translate(` at the call
    site? The enclosing C++ statement is found by walking back at most
    `STATEMENT_LINES` lines to the previous statement boundary (`;`), then the
    literal is matched as the direct source argument:
    ``(?:tr|translate)\s*\(\s*(?:"..."\s*,\s*)? "literal"``.
  * `ts` — does the message exist in the .ts? `exact` when a `<source>` equals
    the (unescaped, whitespace-normalised) string, `fragment` when the row is a
    piece of a longer translated message (the extractor cuts multi-line string
    literals into fragments), `none` otherwise.

Two states are legitimate for `already_wrapped=yes`:
  * `own-call+ts`   — the literal is inside a translate() argument list AND the
                      message (or the longer message it is a piece of) is in the
                      .ts. This is the ONLY yes state (T27);
  * everything else — including `ts-fragment-unwrapped`, a literal that IS a piece
                      of some translated message but sits OUTSIDE the translate()
                      call that owns the statement — is NOT a yes. A fragment hit
                      alone says "this text appears somewhere in a translated
                      message", not "this literal is translated", which is exactly
                      the T39/F3 false claim the verifier exists to catch.

`no-wrap` / `no-ts` rows may NOT claim `already_wrapped=yes`; the generator
treats that as an error instead of copying the input column.
"""
from __future__ import annotations

import html
import pathlib
import re
import xml.etree.ElementTree as ET

STATEMENT_LINES = 12


def load_ts_messages(ts_path: pathlib.Path) -> list[dict[str, object]]:
    """Every .ts message: its source and its `<location>` (file, line) pairs.

    Both location spellings lupdate can write are accepted: the absolute form
    (`<location filename="../src/x.cpp" line="42"/>`) and the RELATIVE form
    (`<location line="+1"/>`, used by `lupdate -locations relative`), where a
    missing filename means "the file of the previous location in this context"
    and a signed line means "this many lines after the previous location". T27
    found the relative form being read as line 1 / file "", which silently
    disabled the fragment check below (`same_file && |line - location_line| <=
    radius` could never hold), so a `.ts` regenerated by lupdate would turn
    correctly wrapped rows into `wrap-only`.
    """
    tree = ET.parse(ts_path)
    messages: list[dict[str, object]] = []
    for context in tree.getroot().findall("context"):
        filename = ""
        line = 0
        for message in context.findall("message"):
            locations: list[tuple[str, int]] = []
            for location in message.findall("location"):
                declared = location.get("filename", "").lstrip("./").removeprefix("../")
                if declared:
                    filename = declared
                raw_line = (location.get("line", "0") or "0").strip()
                if raw_line[:1] in ("+", "-"):
                    line += int(raw_line)
                else:
                    line = int(raw_line or "0")
                if filename:
                    locations.append((filename, line))
            messages.append(
                {"source": message.findtext("source") or "", "locations": locations}
            )
    return messages


def load_ts_sources(ts_path: pathlib.Path) -> list[str]:
    """Every `<source>` of the .ts, XML-unescaped (kept for exact matching)."""
    return [str(message["source"]) for message in load_ts_messages(ts_path)]


def unescape_c(text: str) -> str:
    """Compare the extractor's C escapes with the actual string content."""
    for escaped, actual in (("\\n", "\n"), ("\\t", "\t"), ('\\"', '"'), ("\\\\", "\\")):
        text = text.replace(escaped, actual)
    return text


def normalise(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def _statements(lines: list[str]) -> list[tuple[int, int]]:
    """(start, end) line indexes of the C++ statements (1-based, inclusive)."""
    spans: list[tuple[int, int]] = []
    start = 1
    for index, line in enumerate(lines, 1):
        stripped = line.strip()
        if stripped.endswith(";") or stripped.endswith("{") or stripped.endswith("}"):
            spans.append((start, index))
            start = index + 1
    if start <= len(lines):
        spans.append((start, len(lines)))
    return spans


def find_occurrences(lines: list[str], literal: str) -> list[int]:
    """1-based line numbers holding the quoted literal (prefer translate() lines).

    A C++ message may be a multi-line concatenation (`"first part " "second part"`),
    so the exact literal is tried first and then its leading pieces — the line is
    only a hint; the statement/range test below is what decides the claim.
    """
    for probe in (literal, literal[:60], literal[:40]):
        # No closing quote on purpose: a multi-line C concatenation ends the
        # first literal mid-message, so the probe must match a PREFIX of it.
        quoted = '"' + probe
        hits = [index for index, line in enumerate(lines, 1) if quoted in line]
        if not hits:
            continue
        preferred = [
            index for index in hits if re.search(r"\b(tr|translate)\s*\(", lines[index - 1])
        ]
        return preferred + [index for index in hits if index not in preferred]
    return []


def statement_of(lines: list[str], line: int) -> str:
    """The C++ statement that contains `line` (bounded so a bad hint stays cheap)."""
    for start, end in _statements(lines):
        if start <= line <= end:
            return "\n".join(lines[start - 1 : end])
    return lines[line - 1] if 1 <= line <= len(lines) else ""


def _translate_ranges(statement: str) -> list[tuple[int, int]]:
    """Character ranges of every `tr(...)` / `translate(...)` argument list.

    The scan skips C string literals, because the messages themselves contain
    parentheses (`%1 (%2) — %3 action(s)`) that must not be counted as syntax.
    """
    ranges: list[tuple[int, int]] = []
    for match in re.finditer(r"(?<![\w$.])(?:tr|translate)\s*\(", statement):
        open_index = statement.index("(", match.start())
        depth = 0
        in_string = False
        escape = False
        for index in range(open_index, len(statement)):
            char = statement[index]
            if in_string:
                if escape:
                    escape = False
                elif char == "\\":
                    escape = True
                elif char == '"':
                    in_string = False
                continue
            if char == '"':
                in_string = True
            elif char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
                if depth == 0:
                    ranges.append((open_index, index))
                    break
    return ranges


def wrap_kind(lines: list[str], literal: str, line: int) -> tuple[str, int]:
    """`own-call` | `arg-fragment` | `none`, plus the line the literal was found on.

    `own-call`     the literal sits INSIDE a tr()/translate() argument list (its
                   direct source argument, or a ternary branch of it — both are
                   translated by that call);
    `arg-fragment` the enclosing statement calls translate(), but this literal is
                   outside the argument list (e.g. a fallback `QStringLiteral(...)`
                   passed to `.arg(...)`), so it is NOT translated;
    `none`         no translate()/tr() in the enclosing statement.
    """
    occurrences = find_occurrences(lines, literal)
    if not occurrences:
        return "none", line
    hit = line if line in occurrences else occurrences[0]
    statement = statement_of(lines, hit)
    ranges = _translate_ranges(statement)
    for probe in (literal, literal[:60], literal[:40]):
        quoted = '"' + probe
        position = statement.find(quoted)
        while position != -1:
            if any(start < position < end for start, end in ranges):
                return "own-call", hit
            position = statement.find(quoted, position + 1)
    if re.search(r"(?<![\w$.])(?:tr|translate)\s*\(", statement):
        return "arg-fragment", hit
    return "none", hit


def ts_hit(
    literal: str,
    messages: list[dict[str, object]],
    path: str = "",
    line: int = 0,
    radius: int = 20,
) -> str:
    """`exact` | `fragment` | `none` for one row's string.

    A `fragment` must be a PIECE of a translated multi-line literal **in the same
    file near the call site** — otherwise a shorter, unrelated message that
    happens to be a prefix ("Opened %1" versus the different message
    "Opened %1 line %2" in another lane) would be accepted as translated. The
    `.ts` `<location>` is what tells the two apart.
    """
    text = unescape_c(literal)
    sources = [str(message["source"]) for message in messages]
    if text in sources:
        return "exact"
    target = normalise(text)
    # A short fragment ("still wins.") is still a piece of the translated
    # message; below 8 characters a substring match would be coincidence.
    if len(target) < 8:
        return "none"
    for message in messages:
        source = normalise(str(message["source"]))
        if target not in source:
            continue
        for location, location_line in message["locations"]:  # type: ignore[misc]
            same_file = path.endswith(str(location)) or str(location).endswith(path)
            if same_file and (line == 0 or abs(location_line - line) <= radius):
                return "fragment"
    return "none"


def assess(
    root: pathlib.Path,
    path: str,
    line: int,
    literal: str,
    ts_messages: list[dict[str, object]],
) -> dict[str, str]:
    """The verified state of one row: (verified, wrap, ts, line, statement)."""
    file = root / path
    try:
        lines = file.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return {"verified": "unreadable", "wrap": "none", "ts": "none", "line": str(line)}
    wrap, hit = wrap_kind(lines, literal, line)
    ts = ts_hit(literal, ts_messages, path, hit)
    if wrap == "own-call":
        # The literal IS this call's argument: an exact .ts hit, or a piece of the
        # longer message this call translates, both prove it is translated.
        verified = "own-call+ts" if ts != "none" else "wrap-only"
    elif ts == "fragment":
        # A piece of SOME translated message, but this literal is outside the
        # translate() call of its statement — NOT evidence that this string is
        # translated (T27: the T39/F3 false claim).
        verified = "ts-fragment-unwrapped"
    elif ts == "exact":
        verified = "ts-only"
    else:
        verified = "no-wrap"
    return {
        "verified": verified,
        "wrap": wrap,
        "ts": ts,
        "line": str(hit),
        "statement": normalise(statement_of(lines, hit))[:160],
    }
