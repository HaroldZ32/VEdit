echo "=== version file ==="
grep -E "PACKAGE_VERSION|set\(PACKAGE" /usr/lib/x86_64-linux-gnu/cmake/KF6TextEditor/KF6TextEditorConfigVersion.cmake | head -5
echo "=== upstream requirement evidence (fetched separately, see upstream/) ==="
