echo "## katepart plugin"
find /usr/lib/x86_64-linux-gnu/qt6/plugins -name "*katepart*"
echo "## KSH/KTE libraries"
ls /usr/lib/x86_64-linux-gnu/libKF6TextEditor* /usr/lib/x86_64-linux-gnu/libKF6SyntaxHighlighting*
echo "## ksyntaxhighlighting-data file list (translations only)"
dpkg -L libkf6syntaxhighlighting-data 2>/dev/null | grep -v "/locale/" | head -10
EOS

echo "[t62] 06b-syntax-data-layout.txt"
hdr "06b-syntax-data-layout.txt" "docker run --rm $IMG bash -s (where KSH data lives: embedded vs external)"
in_image >> "$EVID/06b-syntax-data-layout.txt" <<'EOS'
echo "### syntax highlighting data package files (head)"
dpkg -L libkf6syntaxhighlighting-data | head -20
echo "### verilog / themes in the data package"
dpkg -L libkf6syntaxhighlighting-data | grep -iE "verilog|themes/" || echo "(no verilog.xml / themes in the data package)"
echo "### ktexteditor data"
dpkg -L libkf6texteditor-data | head -10
dpkg -L libkf6texteditor-data | grep -i verilog || echo "(no verilog in ktexteditor-data)"
echo "### where the definitions really are"
ls -l /usr/lib/x86_64-linux-gnu/libKF6SyntaxHighlighting.so.6
strings /usr/lib/x86_64-linux-gnu/libKF6SyntaxHighlighting.so.6 | grep -c "systemverilog" || true
EOS

echo "[t62] 07-kate-data-probe.txt"
hdr "07-kate-data-probe.txt" "docker run --rm $IMG bash -s (apt-get download kate-data + dpkg -c listing; version may differ from the original)"
in_image >> "$EVID/07-kate-data-probe.txt" <<'EOS'
cd /tmp && rm -rf katedata && mkdir katedata && cd katedata
apt-get update -qq >/dev/null 2>&1 || true
apt-get download kate-data >/dev/null 2>&1 || echo "(download failed)"
ls -la kate-data*.deb 2>/dev/null || true
dpkg -c kate-data*.deb 2>/dev/null | grep -E "verilog|systemverilog|themes/" | head -10 || echo "(no verilog/systemverilog/themes entries)"
echo "### total syntax xml count in kate-data"
dpkg -c kate-data*.deb 2>/dev/null | grep -c "ksyntaxhighlighting/syntax/.*\.xml" || true
echo "### package version/sha256"
dpkg-deb -f kate-data*.deb Version Package 2>/dev/null || true
sha256sum kate-data*.deb 2>/dev/null || true
EOS

echo "[t62] 08-locked-package-versions.txt (+ self-check against the lock matrix)"
hdr "08-locked-package-versions.txt" "docker run --rm $IMG bash -s (dpkg-query versions for every package in scripts/docker/qt6-locked-packages.txt; version equality asserted)"
in_image >> "$EVID/08-locked-package-versions.txt" <<'EOS'
fail=0
while read -r spec sha rest; do
  case "$spec" in ""|"#"*) continue;; esac
  pkg="${spec%%=*}"
  ver="${spec#*=}"
  got=$(dpkg-query -W -f='${Version}' "$pkg" 2>/dev/null || echo MISSING)
  if [ "$got" = "$ver" ]; then
    printf '%-34s %s   [lock %s] OK\n' "$pkg" "$got" "$ver"
  else
    printf '%-34s %s   [lock %s] MISMATCH\n' "$pkg" "$got" "$ver"
    fail=1
  fi
done < /vedit-build/scripts/docker/qt6-locked-packages.txt
echo
if [ "$fail" -eq 0 ]; then
  echo "SELF-CHECK: PASS — every installed version equals the lock matrix (scripts/docker/qt6-locked-packages.txt)"
else
  echo "SELF-CHECK: FAIL — installed packages diverge from the lock matrix"
fi
exit "$fail"
EOS

echo "[t62] 09-locked-deb-sha256.txt (+ self-check against the lock matrix)"
hdr "09-locked-deb-sha256.txt" "docker run --rm $IMG bash -s (apt-get download every locked package, sha256sum, compare with the lock matrix; 22 packages as of T60)"
in_image >> "$EVID/09-locked-deb-sha256.txt" <<'EOS'
cd /tmp && rm -rf debs && mkdir debs && cd debs
apt-get update -qq >/dev/null 2>&1 || true
fail=0
count=0
while read -r spec sha rest; do
  case "$spec" in ""|"#"*) continue;; esac
  count=$((count + 1))
  pkg="${spec%%=*}"
  if ! apt-get download "$spec" >/dev/null 2>&1; then
    echo "DOWNLOAD-FAILED $spec"
    fail=1
    continue
  fi
  deb=$(ls "${pkg}"_*.deb 2>/dev/null | head -1)
  got=$(sha256sum "$deb" | cut -d' ' -f1)
  if [ "$got" = "$sha" ]; then
    printf '%-60s %s OK\n' "$deb" "$sha"
  else
    printf '%-60s %s MISMATCH (lock %s)\n' "$deb" "$got" "$sha"
    fail=1
  fi
done < /vedit-build/scripts/docker/qt6-locked-packages.txt
echo
echo "## all downloaded .deb sha256 (sorted by name)"
sha256sum *.deb 2>/dev/null | sort -k2
echo
echo "## lock matrix has $count packages"
if [ "$fail" -eq 0 ]; then
  echo "SELF-CHECK: PASS — every downloaded .deb sha256 equals the lock (scripts/docker/qt6-locked-packages.txt)"
else
  echo "SELF-CHECK: FAIL — at least one package could not be downloaded or diverged"
fi
exit "$fail"
EOS

echo "[t62] 10-kf6-cmake-requirements.txt"
hdr "10-kf6-cmake-requirements.txt" "docker run --rm $IMG bash -s (KF6TextEditorConfig.cmake + version file + version headers + ECM)"
in_image >> "$EVID/10-kf6-cmake-requirements.txt" <<'EOS'
