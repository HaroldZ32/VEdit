echo "[t62] 12-ksyntax-definitions-probe.txt"
hdr "12-ksyntax-definitions-probe.txt" "docker run --rm $IMG bash -s (built-in definitions: count, Verilog/SystemVerilog by name, .v filename resolution, themes)"
