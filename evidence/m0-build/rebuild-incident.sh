#!/usr/bin/env bash
# rebuild-incident.sh — regenerate the evidence files lost in the 2026-10-31
# evidence-loss incident (T62).
#
# The originals were captured interactively and are gone (never committed; the
# /tmp backup was per-command isolated). This script REGENERATES what can be
# regenerated from the pinned image + the pinned lock files, and stamps every
# output with a "rebuild after evidence-loss incident" header so nobody can
# mistake it for the pre-incident original.
#
#   bash evidence/m0-build/rebuild-incident.sh
#
# Writes: evidence/m0-build/{01,02,03,04,05,06,06b,07,08,09,10,11,11b,11c,12,13,14,14b}-*.txt
#   (plus a temporary bundle under target/t62-rebuild/, which is gitignored)
# Does NOT touch product code, gates or the lock files.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
EVID="$ROOT/evidence/m0-build"
IMG=vedit-qt6-build:local
TMP="$ROOT/target/t62-rebuild"
IMG_ID=$(docker image inspect "$IMG" --format '{{.Id}}')
mkdir -p "$EVID" "$TMP"

hdr() {
  local file="$1" cmd="$2"
  {
    echo "# rebuild after evidence-loss incident, $(date -Iseconds)"
    echo "# regenerated by: bash evidence/m0-build/rebuild-incident.sh"
    echo "# build image: $IMG ($IMG_ID)"
    echo "# generating command: $cmd"
    echo "# NOT the pre-incident original; see evidence/m0-build/REBUILD-INCIDENT.md"
    echo
  } > "$EVID/$file"
}

in_image() {
  docker run --rm -i -v "$ROOT":/vedit-build -w /vedit-build "$IMG" bash -s
}

echo "[t62] 01-image-facts.txt"
hdr "01-image-facts.txt" "docker run --rm $IMG bash -s (OS/glibc/toolchain/packages/pkg-config/image facts)"
in_image >> "$EVID/01-image-facts.txt" <<'EOS'
echo "## OS"
head -4 /etc/os-release
echo "## glibc"
ldd --version | head -1
echo "## toolchain"
g++ --version | head -1
cmake --version | head -1
ninja --version | sed 's/^/ninja /'
echo "## pkg-config tree-sitter"
pkg-config --modversion tree-sitter
echo "## key package versions (dpkg)"
dpkg-query -W -f='${Package} ${Version}\n' \
  qt6-base-dev qt6-base-dev-tools qt6-declarative-dev qt6-speech-dev \
  libkf6texteditor-dev libkf6syntaxhighlighting-dev libkf6parts-dev libkf6xmlgui-dev \
  libkf6coreaddons-dev libkf6config-dev extra-cmake-modules libtree-sitter-dev libc6 libfuse2t64 2>&1
echo "## cmake package version strings"
grep -m1 'set(PACKAGE_VERSION' /usr/lib/x86_64-linux-gnu/cmake/KF6TextEditor/KF6TextEditorConfigVersion.cmake
echo "## image-recorded facts (/opt/vedit/build-image.txt)"
cat /opt/vedit/build-image.txt 2>/dev/null || echo "(missing)"
EOS

echo "[t62] 02-glibc-loader-probe-raw.txt"
hdr "02-glibc-loader-probe-raw.txt" "docker run --rm $IMG bash -s (loader identity + kernel-version strings + section mapping)"
in_image >> "$EVID/02-glibc-loader-probe-raw.txt" <<'EOS'
LD=/lib/x86_64-linux-gnu/ld-linux-x86-64.so.2
echo "## loader"
ls -l "$LD"
readelf -h "$LD" | grep Type
echo "## 'kernel too old' string in the loader (the search that found nothing: the modern"
echo "## glibc keeps the minimum-kernel value in libc, see below)"
strings -t x "$LD" | grep -n "kernel too old" || echo "(no match in the loader)"
echo "## section mapping of .rodata / .text"
readelf -S -W "$LD" | grep -E "\.rodata|\.text"
echo "## the value glibc 2.43 actually embeds"
strings /lib/x86_64-linux-gnu/libc.so.6 | grep -m1 "Minimum supported kernel"
echo "## ABI note of libc"
readelf -n /lib/x86_64-linux-gnu/libc.so.6 | grep -A1 "ABI-tag" | tail -2
EOS

echo "[t62] 03-elf-isa-notes.txt"
hdr "03-elf-isa-notes.txt" "docker run --rm $IMG bash -s (readelf -n for ISA level/ABI note; NEEDED of KTextEditor)"
in_image >> "$EVID/03-elf-isa-notes.txt" <<'EOS'
for f in /usr/lib/x86_64-linux-gnu/libQt6Core.so.6 /lib/x86_64-linux-gnu/libc.so.6 /usr/lib/x86_64-linux-gnu/libKF6TextEditor.so.6; do
  echo "--- $f"
  readelf -n "$f" 2>/dev/null | sed -n '1,25p'
done
echo "## libKF6TextEditor NEEDED"
readelf -d /usr/lib/x86_64-linux-gnu/libKF6TextEditor.so.6 | sed -n '/NEEDED/p'
EOS

echo "[t62] 04-abi-tag-probe.txt"
hdr "04-abi-tag-probe.txt" "docker run --rm $IMG bash -s (ABI tags of libc/ls/crt, kernel strings, Qt libs)"
in_image >> "$EVID/04-abi-tag-probe.txt" <<'EOS'
for f in /lib/x86_64-linux-gnu/ld-linux-x86-64.so.2 /lib/x86_64-linux-gnu/libc.so.6 /bin/ls /usr/lib/x86_64-linux-gnu/libstdc++.so.6; do
  echo "--- $f"
  grep -a -o -b "kernel too old" "$f" 2>/dev/null | head -3
  readelf -n "$f" 2>/dev/null | grep -A1 "ABI-tag" | tail -2
done
echo "## kernel-related strings in libc (the modern wording)"
strings /lib/x86_64-linux-gnu/libc.so.6 | grep -i "kernel" | head -10
echo "## crt1.o ABI note"
readelf -n /usr/lib/x86_64-linux-gnu/crt1.o 2>/dev/null | sed -n '1,20p'
EOS

echo "[t62] 05-runtime-data-probe.txt"
hdr "05-runtime-data-probe.txt" "docker run --rm $IMG bash -s (QPA plugins, KF6 data dirs, tree-sitter.pc)"
in_image >> "$EVID/05-runtime-data-probe.txt" <<'EOS'
echo "## QPA plugins"
ls /usr/lib/x86_64-linux-gnu/qt6/plugins/platforms/
echo "## kf6 share dirs"
ls /usr/share/kf6 2>/dev/null || echo "(no /usr/share/kf6)"
echo "## ksyntaxhighlighting data (external files: none in this distro package)"
ls /usr/share/ksyntaxhighlighting 2>/dev/null || echo "(no /usr/share/ksyntaxhighlighting — definitions are embedded in the distro library)"
echo "## katepart plugin"
find /usr/lib/x86_64-linux-gnu/qt6/plugins -name "katepart.so"
echo "## tree-sitter pkg-config"
cat /usr/lib/x86_64-linux-gnu/pkgconfig/tree-sitter.pc
EOS

echo "[t62] 06-data-packages.txt"
hdr "06-data-packages.txt" "docker run --rm $IMG bash -s (dpkg data packages + installed KSH/KTE libs)"
in_image >> "$EVID/06-data-packages.txt" <<'EOS'
