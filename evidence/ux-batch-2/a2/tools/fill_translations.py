MESSAGE_RE = re.compile(r"<message>.*?</message>", re.S)


def escape(text: str) -> str:
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def main() -> int:
    text = TS.read_text(encoding="utf-8")
    missing = set()
    filled = 0

    def fill(match: re.Match) -> str:
        nonlocal filled
        block = match.group(0)
        source_match = re.search(r"<source>(.*?)</source>", block, re.S)
        if source_match is None or 'type="unfinished"' not in block:
            return block
        source = html.unescape(source_match.group(1))
        translation = TRANSLATIONS.get(source)
        if translation is None:
            missing.add(source)
            return block
        block = block.replace('<translation type="unfinished"></translation>',
                              "<translation>" + escape(translation) + "</translation>")
        filled += 1
        return block

    text = MESSAGE_RE.sub(fill, text)

    TS.write_text(text, encoding="utf-8")
    print(f"filled={filled} missing={len(missing)}")
    for source in sorted(missing):
        print("MISSING:", source)
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
